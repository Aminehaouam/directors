// npm run validate : post-render QA. Writes output/qa-report.md and output/contact-sheet.png.
// Exit code is non-zero only for real failures (config invalid, no ffmpeg/browser, bad output spec, determinism failure).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { loadConfig, abs, Warnings } from '../lib/config.mjs';
import { startServer, launch, openPage } from '../render/page.mjs';

const argv = process.argv.slice(2), skipVideo = argv.includes('--skip-video');
const lines = [], fails = [], softFails = [], warnings = new Warnings();
const log = (s = '') => { lines.push(s); console.log(s); };
const pass = (name, detail = '') => log(`- PASS  ${name}${detail ? ` — ${detail}` : ''}`);
const fail = (name, detail, hard = true) => { (hard ? fails : softFails).push(`${name}: ${detail}`); log(`- FAIL  ${name} — ${detail}${hard ? '' : '  (not a build failure)'}`); };
const sh = (cmd, args) => spawnSync(cmd, args, { encoding: 'utf8', maxBuffer: 1 << 28 });
const lum = (hex) => { const n = parseInt(hex.slice(1), 16), f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }; return 0.2126 * f(n >> 16) + 0.7152 * f((n >> 8) & 255) + 0.0722 * f(n & 255); };
const contrast = (a, b) => (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);

async function main() {
  const cfg = loadConfig(), P = cfg._palette, tl = cfg._timeline, fps = cfg.fps, total = cfg._frames;
  log(`# QA report — ${cfg.title}`);
  log(`\nGenerated by scripts/validate (deterministic checks; see the brief for the manual design review section below).\n`);
  log('## 1. Output file');
  const vid = abs(cfg.output.final);
  if (skipVideo || !fs.existsSync(vid)) { if (!skipVideo) fail('final MP4 exists', `${cfg.output.final} not found - run npm run render`); else log('- (video checks skipped)'); }
  else {
    const pr = JSON.parse(sh('ffprobe', ['-v', 'error', '-count_frames', '-show_streams', '-show_format', '-of', 'json', vid]).stdout || '{}');
    const v = (pr.streams || []).find((s) => s.codec_type === 'video'), a = (pr.streams || []).find((s) => s.codec_type === 'audio');
    const dur = parseFloat(pr.format?.duration);
    Math.abs(dur - cfg.duration) <= 0.05 ? pass('duration', `${dur.toFixed(3)} s`) : fail('duration', `${dur} s, expected ${cfg.duration} +/- 0.05`);
    v && v.width === 1920 && v.height === 1080 ? pass('resolution', '1920x1080') : fail('resolution', `${v?.width}x${v?.height}`);
    v && v.r_frame_rate === `${fps}/1` && v.avg_frame_rate === `${fps}/1` ? pass('frame rate', `${fps} fps constant`) : fail('frame rate', `${v?.r_frame_rate} / avg ${v?.avg_frame_rate}`);
    v && v.pix_fmt === 'yuv420p' ? pass('pixel format', 'yuv420p') : fail('pixel format', v?.pix_fmt);
    v && v.codec_name === 'h264' ? pass('codec', `H.264 ${v.profile}`) : fail('codec', v?.codec_name);
    +v?.nb_read_frames === total ? pass('frame count', `${v.nb_read_frames}`) : fail('frame count', `${v?.nb_read_frames}, expected ${total}`);
    a && a.codec_name === 'aac' ? pass('audio', `AAC ${a.sample_rate} Hz ${a.channels}ch ${Math.round((a.bit_rate || 0) / 1000)} kbps`) : fail('audio', 'no AAC stream');
    a && Math.abs(parseFloat(a.duration) - dur) <= 0.05 ? pass('audio length matches video', `${parseFloat(a.duration).toFixed(3)} s vs ${dur.toFixed(3)} s`) : fail('audio length matches video', `${a?.duration} vs ${dur}`);
    const bd = sh('ffmpeg', ['-hide_banner', '-i', vid, '-vf', 'blackdetect=d=0.03:pix_th=0.08', '-an', '-f', 'null', '-']);
    const blacks = [...(bd.stderr || '').matchAll(/black_start:([\d.]+) black_end:([\d.]+)/g)].map((m) => `${m[1]}-${m[2]}s`);
    blacks.length ? fail('unintended black frames', blacks.join(', '), false) : pass('no black frames', 'blackdetect found none (the final fade ends on walnut, not black)');
  }

  const { server, port } = await startServer(); const browser = await launch();
  try {
    log('\n## 2. Determinism');
    {
      const hashes = [];
      for (let run = 0; run < 2; run++) {
        const page = await openPage(browser, port, 1), h = [];
        for (const f of [0, 450, 899]) { await page.evaluate((i) => window.renderFrame(i), f); h.push(await page.evaluate(() => window.frameHash())); }
        hashes.push(h); await page.close();
      }
      [0, 450, 899].forEach((f, i) => (hashes[0][i] === hashes[1][i] ? pass(`frame ${f} identical across two fresh renders`, hashes[0][i].slice(0, 16)) : fail(`frame ${f} determinism`, `${hashes[0][i].slice(0, 12)} != ${hashes[1][i].slice(0, 12)}`)));
    }

    const page = await openPage(browser, port, 0.5);
    log('\n## 3. Fonts');
    pass('all vendored fonts loaded from public/fonts', page.__fonts ? '' : (await page.evaluate(() => window.info.fonts)).join(', '));
    const fx = await page.evaluate(() => window.footageInfo());
    const standIns = Object.entries(fx).filter(([, v]) => !v.present).map(([k]) => k);

    // ---- sampled pass: text boxes, safe margins, green cap
    const sm = cfg.typography.safeMargins, SAFE = { x0: sm.left, x1: 1920 - sm.right, y0: sm.top, y1: 1080 - sm.bottom };
    const byId = {}, greenByShot = {}, marginViol = {};
    const shotOf = (t) => (cfg.shots.find((s) => t >= s.start && t < s.end) || cfg.shots[cfg.shots.length - 1]).n;
    for (let f = 0; f < total; f += 3) {
      await page.evaluate((i) => window.renderFrame(i), f);
      const boxes = await page.evaluate(() => window.textBoxes()), gf = await page.evaluate(() => window.greenFraction()), n = shotOf(f / fps);
      greenByShot[n] = Math.max(greenByShot[n] || 0, gf);
      for (const b of boxes) {
        const e = (byId[b.id] ||= { best: null, first: f });
        if (!e.best || b.alpha > e.best.alpha + 1e-6) e.best = { ...b, frame: f };
        if (b.alpha >= 0.9 && !b.id.startsWith('standin-') && (b.x < SAFE.x0 - 1 || b.x + b.w > SAFE.x1 + 1 || b.y < SAFE.y0 - 1 || b.y + b.h > SAFE.y1 + 1)) marginViol[b.id] = { f, b };
      }
    }
    log('\n## 4. Safe margins (96 px left/right, 72 px top/bottom)');
    const mv = Object.entries(marginViol);
    if (!mv.length) pass('every text bounding box stays inside the safe margins', `${Object.keys(byId).length} text elements checked`);
    for (const [id, { f, b }] of mv) fail(`safe margin: ${id}`, `frame ${f} box x ${b.x.toFixed(0)}..${(b.x + b.w).toFixed(0)}, y ${b.y.toFixed(0)}..${(b.y + b.h).toFixed(0)}`, false);

    log('\n## 5. Text contrast (>= 4.5:1 against the sampled background behind each text box)');
    const rows = [];
    for (const [id, e] of Object.entries(byId)) {
      const b = e.best; if (b.alpha < 0.5) continue;
      await page.evaluate(([i]) => window.renderFrame(i, { noText: true }), [b.frame]);
      const s = await page.evaluate(([x, y, w, h]) => window.sampleLuminance(x, y, w, h), [b.x, b.y, b.w, b.h]);
      const tl_ = lum(b.color), c = contrast(tl_, s.mean), worst = Math.min(contrast(tl_, s.min), contrast(tl_, s.max));
      rows.push({ id, c, worst, frame: b.frame });
      c >= 4.5 ? pass(`${id}`, `${c.toFixed(1)}:1 (worst pixel ${worst.toFixed(1)}:1) @ frame ${b.frame}`) : fail(`contrast ${id}`, `${c.toFixed(2)}:1 @ frame ${b.frame}`, false);
    }

    log('\n## 6. Text entrance lead (lands 80-120 ms before its spoken cue, +/- one frame)');
    const lead = cfg.motion.textLeadSeconds, tol = 1 / fps + 1e-6;
    for (const e of Object.values(tl.events).filter((x) => x.text && x.wordAt !== null)) {
      const tid = e.textId || e.id;
      let vis = null, full = null;
      for (let f = Math.floor((e.t0 - 0.3) * fps); f <= Math.ceil((e.t1 + 0.3) * fps) && f < total; f++) {
        if (f < 0) continue;
        await page.evaluate((i) => window.renderFrame(i), f);
        const b = (await page.evaluate(() => window.textBoxes())).find((x) => x.id === tid);
        if (b && vis === null && b.alpha > 0.02) vis = f / fps;
        if (b && full === null && b.alpha >= 0.98) { full = f / fps; break; }
      }
      const landing = e.align === 'end' ? full : vis, L = landing === null ? NaN : e.wordAt - landing;
      L >= lead[0] - tol && L <= lead[1] + tol ? pass(`${e.id}`, `entrance ${(L * 1000).toFixed(0)} ms before "${e.atWord}" (${e.atCue})`) : fail(`text lead ${e.id}`, `${(L * 1000).toFixed(0)} ms (want ${lead[0] * 1000}-${lead[1] * 1000} ms)`, false);
    }

    log('\n## 7. Green rule (green leaks as ink: <= ~12% of any frame; <= ~30% in shot 10)');
    for (const s of cfg.shots) {
      const cap = s.n === 10 ? cfg.greenCap.shot10 : cfg.greenCap.default, g = greenByShot[s.n] || 0;
      g <= cap ? pass(`shot ${s.n}`, `peak ${(g * 100).toFixed(1)}% (cap ${(cap * 100).toFixed(0)}%)`) : fail(`green cap shot ${s.n}`, `peak ${(g * 100).toFixed(1)}% > ${(cap * 100).toFixed(0)}%`, false);
    }
    await page.close();

    log('\n## 8. Footage and audio status');
    log(standIns.length ? `- Footage stand-ins in use for slot(s): ${standIns.join(', ')} (illustrated, stamped SOURCE SHOT REQUIRED).` : '- All footage slots supplied.');
    for (const f of [cfg.voiceover.path, cfg.music.path]) log(`- ${f}: ${fs.existsSync(abs(f)) ? 'present' : 'MISSING (silent / placeholder used)'}`);
    log(`- sfx placeholders: ${cfg.sfx.filter((s) => !fs.existsSync(abs(s.path))).length} of ${cfg.sfx.length}`);

    log('\n## 9. Contact sheet');
    const frameDir = abs(`${cfg.output.frames}/final`);
    if (!fs.existsSync(path.join(frameDir, '0000.png'))) log('- skipped (no full-resolution frames in output/frames/final)');
    else {
      const imgs = [], rel = (i) => `file://${frameDir}/${String(Math.min(total - 1, Math.max(0, i))).padStart(4, '0')}.png`;
      const shotCells = cfg.shots.map((s) => `<figure><img src="${rel(Math.round(((s.start + s.end) / 2) * fps))}"><figcaption>SHOT ${s.n} &middot; ${((s.start + s.end) / 2).toFixed(2)}s</figcaption></figure>`).join('');
      const trCells = tl.transitions.filter((x) => x.type !== 'cut').map((x) => `<div class="strip"><h3>${x.id} &middot; ${x.type} &middot; ${x.from} to ${x.to}</h3>${[-0.12, 0.25, 0.5, 0.75, 1.1].map((k) => `<figure><img src="${rel(Math.round((x.t0 + (x.t1 - x.t0) * Math.min(1, Math.max(0, k)) + (k < 0 ? k : 0) + (k > 1 ? k - 1 : 0)) * fps))}"><figcaption>${k < 0 ? 'before' : k > 1 ? 'after' : Math.round(k * 100) + '%'}</figcaption></figure>`).join('')}</div>`).join('');
      const html = `<html><body style="margin:0;background:#171714;color:#E6D2AC;font:14px Inter,sans-serif;padding:16px;width:1960px"><h2 style="margin:0 0 8px">Contact sheet — midpoint of each shot</h2><div style="display:grid;grid-template-columns:repeat(4,480px);gap:8px">${shotCells}</div><h2 style="margin:18px 0 8px">Before/after strips around each transition</h2>${trCells}<style>figure{margin:0}img{width:480px;height:270px;display:block}figcaption{padding:2px 0 6px;font-size:12px;letter-spacing:.08em}.strip{display:flex;gap:8px;flex-wrap:wrap;margin-bottom:6px}.strip h3{width:100%;margin:6px 0 2px;font-size:13px}.strip img{width:372px;height:209px}</style></body></html>`;
      const cp = await browser.newPage({ viewport: { width: 1960, height: 1200 } });
      const tmp = abs(`${cfg.output.cache}/contact.html`); fs.writeFileSync(tmp, html);
      await cp.goto(`file://${tmp}`); await cp.waitForLoadState('load');
      await cp.screenshot({ path: abs(cfg.output.contactSheet), fullPage: true }); await cp.close();
      pass('contact-sheet.png written', cfg.output.contactSheet);
    }
  } finally { await browser.close(); server.close(); }

  log('\n## Summary');
  log(fails.length ? `- ${fails.length} real failure(s): ${fails.join('; ')}` : '- No real failures (output spec, determinism).');
  log(softFails.length ? `- ${softFails.length} design/QA finding(s) open:\n${softFails.map((s) => `  - ${s}`).join('\n')}` : '- No open design/QA findings.');
  fs.mkdirSync(path.dirname(abs(cfg.output.qaReport)), { recursive: true });
  const revision = abs('docs/REVISION_NOTES.md');
  fs.writeFileSync(abs(cfg.output.qaReport), lines.join('\n') + '\n' + (fs.existsSync(revision) ? `\n---\n\n${fs.readFileSync(revision, 'utf8')}` : ''));
  console.log(`\nQA report: ${cfg.output.qaReport}`);
  if (fails.length) process.exitCode = 1;
}
main().catch((e) => { console.error(`\nERROR (validate): ${e.message}`); process.exit(1); });
